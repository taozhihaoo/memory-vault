export function normalizeLang(value) {
  const v = String(value || "").toLowerCase();
  if (v.startsWith("zh") || v === "cn" || v === "chinese") return "zh";
  if (v.startsWith("en") || v === "english") return "en";
  return null;
}

/** Resolve language: explicit ?lang= > saved preference > browser > English. */
export function detectLanguage({ search = "", stored = "", browser = "" } = {}) {
  const fromUrl = normalizeLang(new URLSearchParams(search).get("lang"));
  if (fromUrl) return fromUrl;
  const fromStorage = normalizeLang(stored);
  if (fromStorage) return fromStorage;
  return normalizeLang(browser) || "en";
}

/** Translate a key, with {name} interpolation and an English fallback. */
export function t(lang, key, vars = {}) {
  const table = DICT[lang] || DICT.en;
  let text = table[key] ?? DICT.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

/** Keys present in one language but missing in another (used by tests/CI). */
export function missingKeys(source = "en", target = "zh") {
  const a = Object.keys(DICT[source] || {});
  const b = new Set(Object.keys(DICT[target] || {}));
  return a.filter((key) => !b.has(key));
}
